#define FLASH_BASE  0x52002000

///////////////////////////////////////////////////////////////////////////////

/* FLASH_ACR */
#define FLASH_ACR_OFFSET  0x000
#define FLASH_ACR         (FLASH_BASE + FLASH_ACR_OFFSET)

/* FLASH_ACR_WRHIGHFREQ */
#define FLASH_ACR_WRHIGHFREQ_OFFSET   4

#define FLASH_ACR_WRHIGHFREQ_0  (0  <<  FLASH_ACR_WRHIGHFREQ_OFFSET)
#define FLASH_ACR_WRHIGHFREQ_1  (1  <<  FLASH_ACR_WRHIGHFREQ_OFFSET)
#define FLASH_ACR_WRHIGHFREQ_2  (2  <<  FLASH_ACR_WRHIGHFREQ_OFFSET)

/* FLASH_ACR_LATENCY */
#define FLASH_ACR_LATENCY_OFFSET  0

#define FLASH_ACR_LATENCY_WS_0  (0  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_1  (1  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_2  (2  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_3  (3  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_4  (4  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_5  (5  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_6  (6  <<  FLASH_ACR_LATENCY_OFFSET)
#define FLASH_ACR_LATENCY_WS_7  (7  <<  FLASH_ACR_LATENCY_OFFSET)
