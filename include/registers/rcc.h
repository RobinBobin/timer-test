#define RCC_APB1LENR      (RCC_BASE + 0x0E8)
#define RCC_C1_APB1LENR   (RCC_BASE + 0x148)
#define RCC_C2_APB1LENR   (RCC_BASE + 0x1A8)

#define RCC_APB1LENR_TIM6_ENABLED   (1 << 4)
